"""Write THIRD_PARTY_NOTICES.md from the installed, pinned dependencies.

Python: every package in requirements.lock.txt, read from the installed package metadata.
Web: every non-dev package in apps/web/package-lock.json, read from node_modules (run `npm ci` first).

Usage: python tools/third_party_notices.py [--check]
"""

from __future__ import annotations

import json
import re
import sys
from importlib import metadata
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "THIRD_PARTY_NOTICES.md"
# Platform-specific packages that may be absent where this runs (from their published metadata).
NOT_INSTALLED = {"colorama": "BSD-3-Clause (Windows only)"}


def _python_license(dist: metadata.Distribution) -> str:
    expr = dist.metadata.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split("::")[-1].strip() for c in dist.metadata.get_all("Classifier") or []
                   if c.startswith("License ::") and "OSI Approved" != c.split("::")[-1].strip()]
    if classifiers:
        return "; ".join(sorted(set(classifiers)))
    text = (dist.metadata.get("License") or "").strip().splitlines()
    if text:
        return text[0][:80]
    bundled = next((f for f in dist.files or [] if f.name.upper().startswith(("LICENSE", "COPYING"))), None)
    if bundled is not None:
        first = (bundled.read_text() or "").strip().splitlines()
        return f"{first[0][:60]} (licence file)" if first else "see package"
    return "see package"


def python_rows() -> list[tuple[str, str, str]]:
    rows = []
    for line in (REPO / "requirements.lock.txt").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^([A-Za-z0-9_.\-]+)==([^\s;]+)", line)
        if not m:
            continue
        name, version = m.groups()
        try:
            lic = _python_license(metadata.distribution(name))
        except metadata.PackageNotFoundError:
            lic = NOT_INSTALLED.get(name.lower(), "not installed here (platform-specific)")
        rows.append((name, version, lic))
    return rows


def web_rows() -> list[tuple[str, str, str]]:
    lock = json.loads((REPO / "apps/web/package-lock.json").read_text(encoding="utf-8"))
    rows = []
    for path, info in sorted(lock.get("packages", {}).items()):
        if not path.startswith("node_modules/") or info.get("dev") or info.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        pkg = REPO / "apps/web" / path / "package.json"
        lic = info.get("license") or (json.loads(pkg.read_text(encoding="utf-8")).get("license") if pkg.is_file() else None)
        rows.append((name, info.get("version", "?"), lic or "see package"))
    return rows


def render() -> str:
    def table(rows: list[tuple[str, str, str]]) -> list[str]:
        return ["| Package | Version | Licence |", "|---|---|---|", *[f"| {n} | {v} | {lic} |" for n, v, lic in rows]]

    return "\n".join([
        "# Third-party notices",
        "",
        "Adaptive IDS itself is proprietary (see `LICENSE`). It depends on the open-source packages below,",
        "which are **not** part of this repository: they are installed from the pinned lock files and remain",
        "under their own licences. Generated by `python tools/third_party_notices.py`.",
        "",
        "## Python (requirements.lock.txt)",
        "",
        *table(python_rows()),
        "",
        "## Web app runtime (apps/web/package-lock.json, production dependencies)",
        "",
        *table(web_rows()),
        "",
        "Development-only tools (test runners, type checker, bundler) are not shipped in the built web app",
        "and are not listed.",
        "",
    ])


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.is_file() and OUT.read_text(encoding="utf-8") == text else 1)
    OUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUT.name}")
